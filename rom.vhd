library ieee;
  use ieee.std_logic_1164.all;
  use ieee.numeric_std.all;

entity rom is
  port (clk      : in  std_logic;
        endereco : in  unsigned(6 downto 0);
        dado     : out unsigned(15 downto 0)
       );
end entity;

architecture a_rom of rom is
  type mem is array (0 to 127) of unsigned(15 downto 0);
  constant conteudo_rom : mem := (
    -- caso endereco => conteudo
    0      => B"0010_111_000000000",   -- LD A, 0
    1      => B"0010_001_000000001",   -- LD R1, 1
    2      => B"0101_011_111_010_001", -- MV R3, A
    3      => B"1101_111_011_000000",  -- SW R3, A
    4      => B"0101_111_001_111_111", -- ADD A, A, R1
    5      => B"1001_111_000100000",   -- CMPI A, 32
    6      => B"1100_00000010_1_101",  -- BGE 2
    7      => B"1111_11111_0000001",   -- JUMP 1

    8      => B"0010_000_000000111",   -- LD R0, 7
    9      => B"0010_001_000010011",   -- LD R1, 19
    10     => B"0010_010_000010001",   -- LD R2, 17
    11     => B"0010_011_001010111",   -- LD R3, 87
    12     => B"0010_100_010000001",   -- LD R4, 129
    13     => B"0010_101_111101100",   -- LD R5, -20
    14     => B"0010_111_000101100",   -- LD A, 44
    15     => B"1101_111_101_000000",  -- SW R5, A
    16     => B"0010_111_001111100",   -- LD A, 124
    17     => B"1101_111_000_000000",  -- SW R0, A
    18     => B"0010_111_001100011",   -- LD A, 99
    19     => B"1101_111_001_000000",  -- SW R1, A
    20     => B"0010_111_001000001",   -- LD A, 65
    21     => B"1101_111_011_000000",  -- SW R3, A
    22     => B"0010_111_000010110",   -- LD A, 22
    23     => B"1101_111_100_000000",  -- SW R4, A
    24     => B"0010_111_000000011",   -- LD A, 3
    25     => B"1101_111_010_000000",  -- SW R2, A

    26     => B"0010_011_000000000",   -- LD R3, 0
    27     => B"0010_001_000000001",   -- LD R1, 1
    28     => B"0101_111_011_010_001", -- MV A, R3
    29     => B"0011_011_111_000000",  -- LW R3, A
    30     => B"0101_111_001_111_111", -- ADD A, A, R1
    31     => B"1001_111_010000000",   -- CMPI A, 128
    32     => B"1100_00000010_1_101",  -- BGE 2
    33     => B"1111_11111_0011101",   -- JUMP 29

    34     => B"0010_111_000010110",   -- LD A, 22
    35     => B"0011_010_111_000000",  -- LW R2, A
    36     => B"0010_111_001000001",   -- LD A, 65
    37     => B"0011_101_111_000000",  -- LW R5, A
    38     => B"0010_111_000000011",   -- LD A, 3
    39     => B"0011_001_111_000000",  -- LW R1, A
    40     => B"0010_111_000101100",   -- LD A, 44
    41     => B"0011_000_111_000000",  -- LW R0, A
    42     => B"0010_111_001111100",   -- LD A, 124
    43     => B"0011_011_111_000000",  -- LW R3, A
    44     => B"0010_111_001100011",   -- LD A, 99
    45     => B"0011_100_111_000000",  -- LW R4, A
    others => (others => '0')
  );

begin
  process (clk)
  begin
    if (rising_edge(clk)) then
      dado <= conteudo_rom(to_integer(endereco));
    end if;
  end process;
end architecture;
